import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";

/**
 * این پرامپت یک "قانون سبک" (style guide) برای خلاصه‌سازی و پرسش‌وپاسخ فارسیه —
 * نه یه ابزار جدید برای گرفتن داده. هدفش اینه که خروجی نهایی Claude:
 *  ۱. ترجمه‌ی تحت‌اللفظی/کلمه‌به‌کلمه نباشه.
 *  ۲. ساختار جمله‌بندی متن مبدأ (انگلیسی یا ژاپنی) رو کپی نکنه.
 *  ۳. اصطلاحات تخصصی رو به‌درستی و یکدست مدیریت کنه.
 *
 * معمولاً این پرامپت رو کنار jstage_research_plan (یا هر ابزار دیگه‌ای که متن/چکیده
 * برمی‌گردونه) به Claude می‌دی تا قبل از نوشتن خروجی نهایی، این قوانین رو رعایت کنه.
 */

const LENGTH_GUIDE: Record<string, string> = {
  short:
    "خلاصه باید در حد ۳ تا ۵ جمله باشه — فقط مهم‌ترین یافته و نتیجه، بدون جزئیات روش‌شناسی.",
  medium:
    "خلاصه باید یک یا دو پاراگراف باشه — هدف پژوهش، روش کلی، مهم‌ترین یافته‌ها و نتیجه‌گیری.",
  detailed:
    "خلاصه باید ساختاریافته و کامل باشه — شامل زمینه/هدف، روش، یافته‌های کلیدی (با اعداد/آمار مهم اگه بود)، و نتیجه‌گیری، هرکدوم در یک بند جدا.",
};

export function registerPersianSummaryStylePrompt(server: McpServer): void {
  server.registerPrompt(
    "persian_summary_style",
    {
      title: "راهنمای سبک خلاصه‌سازی و پاسخ‌دهی فارسی",
      description:
        "قوانین الزامی برای تبدیل متن انگلیسی/ژاپنی مقاله به خلاصه یا پاسخ فارسیِ روان و غیر تحت‌اللفظی. " +
        "این پرامپت رو معمولاً همراه با محتوایی که از fetchArticleText یا ابزارهای PubMed گرفتی به کار ببر.",
      argsSchema: {
        content: z
          .string()
          .describe(
            "متن مبدأ (انگلیسی یا ژاپنی) که باید طبق این قوانین به فارسی خلاصه/پاسخ داده بشه — " +
              "مثلاً abstract یا بخشی از نتایج که قبلاً با ابزارهای دیگه گرفتی"
          ),
        length: z
          .enum(["short", "medium", "detailed"])
          .default("medium")
          .describe("سطح جزئیات خلاصه‌ی نهایی"),
        audience: z
          .enum(["general", "expert"])
          .default("expert")
          .describe(
            "general = خواننده‌ی عمومی/غیرمتخصص (اصطلاحات باید ساده‌سازی بشن)؛ " +
              "expert = خواننده‌ی متخصص همون حوزه (اصطلاحات تخصصی رایج حفظ بشن)"
          ),
      },
    },
    async ({ content, length, audience }) => {
      const lengthNote = LENGTH_GUIDE[length];

      const audienceNote =
        audience === "general"
          ? "مخاطب غیرمتخصصه — اصطلاحات تخصصی رو در همون بار اول با یک توضیح خیلی کوتاه داخل پرانتز همراه کن."
          : "مخاطب متخصص همون حوزه‌ست — نیازی به توضیح پایه‌ای اصطلاحات نیست، فقط از معادل‌های رایج و جاافتاده استفاده کن.";

      const rules = [
        "۱. هرگز جمله‌به‌جمله ترجمه نکن. اول کل مفهوم و منطق علمی متن رو بفهم، بعد اون مفهوم رو با ساختار جمله‌بندی طبیعیِ فارسی از نو بنویس.",
        "۲. ترتیب و طول جمله‌های متن مبدأ رو کپی نکن — ساختار پاراگراف فارسی می‌تونه کاملاً متفاوت از ساختار انگلیسی/ژاپنی باشه.",
        "۳. اصطلاحات تخصصی جاافتاده (مثل CRISPR، PCR، DNA) رو به همون شکل رایج (انگلیسی یا فارسیِ متداول) نگه دار؛ اصطلاحاتی که معادل رایج فارسی دارن رو حتماً فارسی بنویس.",
        "۴. اگه متن مبدأ ژاپنیه، مراقب باش اصطلاحات و اعداد (به‌خصوص سال، درصد، nهای نمونه) درست و بدون خطای تبدیل واحد منتقل بشن.",
        "۵. از عبارات پرکن یا زینتی که در متن اصلی نبوده استفاده نکن — خلاصه نباید حجیم‌تر یا احساسی‌تر از لحن علمی متن اصلی باشه.",
        "۶. اگه بخشی از متن مبدأ مبهم یا ناقص بود (مثلاً چون abstract کامل در دسترس نبود)، این ابهام رو صادقانه ذکر کن، حدس نزن.",
        "۷. اگه ارجاع/DOI برای متن مبدأ در دسترسه، انتهای خلاصه لینک/DOI رو هم بیار.",
      ];

      return {
        messages: [
          {
            role: "user" as const,
            content: {
              type: "text" as const,
              text: [
                "## 📝 قوانین سبک خلاصه‌سازی فارسی",
                "",
                `سطح جزئیات: **${length}** — ${lengthNote}`,
                `مخاطب: **${audience}** — ${audienceNote}`,
                "",
                "### قوانین الزامی:",
                ...rules,
                "",
                "### متن مبدأ برای خلاصه‌سازی/پاسخ:",
                "```",
                content,
                "```",
              ].join("\n"),
            },
          },
        ],
      };
    }
  );
}
